/**
 * Copies the Admin API contract schemas (zod) from a local WorkAdventure checkout into
 * src/lib/contract/workadventure, so this admin validates its answers against the exact schemas
 * the pusher and the back parse them with.
 *
 *   npm run contract:sync            # copy
 *   npm run contract:check           # fail (exit 1) if the vendored copy drifted from the checkout
 *
 * The checkout defaults to ../workadventure; override it with WORKADVENTURE_REPO.
 */
import { readFile, readdir, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const repo = path.resolve(process.env.WORKADVENTURE_REPO ?? path.join(process.cwd(), "..", "workadventure"));
const sourceDir = path.join(repo, "libs/messages/src/JsonMessages");
const targetDir = path.join(process.cwd(), "src/lib/contract/workadventure");
const check = process.argv.includes("--check");

const HEADER = (file: string) =>
    `// Vendored from WorkAdventure (libs/messages/src/JsonMessages/${file}) by scripts/sync-contract.ts.\n` +
    `// Do not edit: run "npm run contract:sync" instead. License: see the WorkAdventure repository.\n`;

async function main(): Promise<void> {
    if (!existsSync(sourceDir)) {
        console.error(`WorkAdventure checkout not found at ${repo}. Set WORKADVENTURE_REPO.`);
        process.exit(check ? 0 : 1);
    }
    await mkdir(targetDir, { recursive: true });

    const files = (await readdir(sourceDir)).filter((f) => f.endsWith(".ts")).sort();
    const drifted: string[] = [];

    for (const file of files) {
        const expected = HEADER(file) + (await readFile(path.join(sourceDir, file), "utf8"));
        const target = path.join(targetDir, file);
        const current = existsSync(target) ? await readFile(target, "utf8") : undefined;
        if (current === expected) continue;
        if (check) {
            drifted.push(file);
        } else {
            await writeFile(target, expected);
            console.info(`synced ${file}`);
        }
    }

    let commit = "unknown";
    try {
        commit = execFileSync("git", ["-C", repo, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
    } catch {
        // Not a git checkout: keep "unknown".
    }
    const index =
        `// Generated by scripts/sync-contract.ts. Do not edit.\n` +
        files.map((f) => `export * from "./${f.replace(/\.ts$/, "")}";`).join("\n") +
        `\nexport const WORKADVENTURE_CONTRACT_COMMIT = ${JSON.stringify(commit)};\n`;

    if (check) {
        if (drifted.length > 0) {
            console.error(`Contract drift with ${repo}: ${drifted.join(", ")}. Run "npm run contract:sync".`);
            process.exit(1);
        }
        console.info("Contract is in sync with the WorkAdventure checkout.");
        return;
    }
    await writeFile(path.join(targetDir, "index.ts"), index);
    console.info(`Contract synced from ${repo} @ ${commit}`);
}

await main();
